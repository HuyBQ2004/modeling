    private long getHikariPending() {
        try {
            if (dataSource instanceof HikariDataSource h) {
                HikariPoolMXBean b = h.getHikariPoolMXBean();
                if (b != null) return b.getThreadsAwaitingConnection();
            }
        } catch (Exception ignored) {
        }
        return 0;
    }

    private void setPoolSize(int size) throws Exception {
        if (dataSource instanceof HikariDataSource h) {
            h.setMaximumPoolSize(size);
            h.setMinimumIdle(Math.min(size / 4 + 1, size));
            Thread.sleep(500);
        } else throw new IllegalStateException("DataSource is not HikariDataSource");
    }

