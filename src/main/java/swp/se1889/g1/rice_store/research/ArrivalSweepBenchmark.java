    /**
     * Snapshot of all GarbageCollectorMXBean counters at a point in time.
     * Delta between two snapshots gives GC events and pause time during a window.
     * This uses the standard java.lang.management API (no JFR agent required).
     */
    private GcSnapshot snapshotGc() {
        long totalCollections = 0;
        long totalPauseMs = 0;
        for (GarbageCollectorMXBean gc : ManagementFactory.getGarbageCollectorMXBeans()) {
            long count = gc.getCollectionCount();
            long time = gc.getCollectionTime();
            if (count > 0) totalCollections += count;
            if (time > 0) totalPauseMs += time;
        }
        return new GcSnapshot(totalCollections, totalPauseMs);
    }

