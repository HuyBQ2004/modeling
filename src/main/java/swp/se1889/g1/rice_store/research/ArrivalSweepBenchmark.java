    @Override
    public void run(String... args) throws Exception {
        System.out.println("============================================================");
        System.out.println("  ARRIVAL SWEEP BENCHMARK  (open-loop Poisson, rho-targeted)");
        System.out.printf("  pool=%d  reps=%d  warmup=%ds  measure=%ds%n",
                POOL_SIZE, REPS, WARMUP_SECONDS, MEASURE_SECONDS);
        System.out.println("============================================================");

        estimateMu();

        // --- PHASE 1: freeze predictions BEFORE any sweep measurement (Framework §6) ---
        Map<Double, Prediction> predictions = new LinkedHashMap<>();
        try (PrintWriter w = openCsv(FILE_PRED)) {
            w.println("Rho_Target,Lambda_Target_rps,Model_P_wait,Model_E_Nq," +
                    "Model_E_Wq_ms,Model_Mean_Latency_ms,Model_Region,Model_Valid");
            for (double rho : RHO_TARGETS) {
                Prediction p = predict(rho);
                predictions.put(rho, p);
                w.printf(Locale.US, "%.2f,%.2f,%.4f,%.2f,%.2f,%.2f,%s,%s%n",
                        rho, p.lambda, p.pWait, p.eNq, p.eWqMs, p.meanLatencyMs,
                        p.region, p.steadyStateValid ? "YES" : "NO_(rho>=1)");
                System.out.printf(
                        "  [PRED] rho=%.2f  lambda=%.1f rps  P(wait)=%.3f  E[Nq]=%.1f  E[W]=%.1f ms  %s%n",
                        rho, p.lambda, p.pWait, p.eNq, p.meanLatencyMs, p.region);
            }
        }
        writeBoundaryPredictions();

        // --- PHASE 2: randomized measurement cells ---
        List<Cell> cells = new ArrayList<>();
        for (Mode m : Mode.values())
            for (double rho : RHO_TARGETS)
                for (int rep = 1; rep <= REPS; rep++)
                    cells.add(new Cell(m, rho, rep));
        Collections.shuffle(cells, new Random(RANDOM_ORDER_SEED));

        Map<String, List<RunResult>> byCell = new LinkedHashMap<>();
        try (PrintWriter raw = openCsv(FILE_RAW)) {
            raw.println("Mode,Rho_Target,Rep,Lambda_Target_rps,Lambda_Achieved_rps," +
                    "InterArrival_CV,Dispatched,Completed,Rejected,Success_Pct," +
                    "Throughput_rps,Mean_Latency_ms,P99_ms," +
                    "Nq_Hikari_Mean,Nq_Hikari_Max,Little_Nq_Check," +
                    "Heap_Mean_MB,Heap_Max_MB,Threads_Mean,Threads_Max," +
                    // === JFR / GC evidence columns (Phase 1 addition) ===
                    "GC_Collections,GC_Pause_Total_ms,GC_Pause_Mean_ms," +
                    "Alloc_Rate_MB_s,Heap_Delta_MB");
            int i = 0;
            for (Cell cell : cells) {
                i++;
                System.out.printf("%n[%d/%d] mode=%s rho=%.2f rep=%d%n",
                        i, cells.size(), cell.mode, cell.rho, cell.rep);
                RunResult r = runCell(cell.mode, predictions.get(cell.rho).lambda);
                writeRawRow(raw, cell, r);
                byCell.computeIfAbsent(cell.mode + "|" + cell.rho, k -> new ArrayList<>()).add(r);
            }
        }

        // --- PHASE 3: aggregate + validate against frozen predictions ---
        writeSummaryAndValidation(byCell, predictions);

        System.out.println("\n============================================================");
        System.out.printf("  DONE. mu=%.4f req/s/conn (E[S]=%.1f ms)%n", mu, 1000.0 / mu);
        System.out.printf("  Files: %s%n         %s%n         %s%n         %s%n         %s%n",
                FILE_PRED, FILE_BOUND, FILE_RAW, FILE_SUMMARY, FILE_VAL);
        System.out.println("============================================================");
    }

    // ===================================================================
    // mu ESTIMATION (rho ~ 0)
    // ===================================================================

    private void estimateMu() throws Exception {
        System.out.println("\n--- Baseline: estimating mu at rho~0 ---");
        System.gc();
        Thread.sleep(2000);
        baselineHeapMb = captureSystem().heapMb;

        setPoolSize(BASELINE_POOL);

        // JIT + connection-establishment warmup, excluded from E[S] estimation.
        // Without this, baseline E[S] was inflated ~20% vs steady-state (75 vs 63 ms).
        ExecutorService warm = Executors.newVirtualThreadPerTaskExecutor();
        CountDownLatch warmLatch = new CountDownLatch(100);
        for (int i = 0; i < 100; i++) {
            warm.submit(() -> {
                try {
                    performIoTask();
                } catch (Exception ignored) {
                } finally {
                    warmLatch.countDown();
                }
            });
        }
        warmLatch.await(120, TimeUnit.SECONDS);
        warm.shutdownNow();

        ExecutorService ex = Executors.newVirtualThreadPerTaskExecutor();
        List<Long> lats = Collections.synchronizedList(new ArrayList<>());
        Semaphore gate = new Semaphore(BASELINE_CONCURRENT);
        CountDownLatch latch = new CountDownLatch(BASELINE_SAMPLES);
        for (int i = 0; i < BASELINE_SAMPLES; i++) {
            gate.acquire();
            ex.submit(() -> {
                long t = System.nanoTime();
                try {
                    performIoTask();
                } catch (Exception ignored) {
                } finally {
                    lats.add(System.nanoTime() - t);
                    gate.release();
                    latch.countDown();
                }
            });
        }
        latch.await(120, TimeUnit.SECONDS);
        ex.shutdownNow();

        baselineMeanMs = lats.stream().mapToLong(Long::longValue).average()
                .orElse(SIMULATED_LATENCY_MS * 1_000_000.0) / 1_000_000.0;
        mu = 1000.0 / baselineMeanMs;
        System.out.printf("  E[S]=%.1f ms  ->  mu=%.4f req/s/conn  (n=%d samples, idle heap=%d MB)%n",
                baselineMeanMs, mu, lats.size(), baselineHeapMb);
    }

    // ===================================================================
    // PREDICTIONS
    // ===================================================================

    private Prediction predict(double rhoTarget) {
        double lambda = rhoTarget * POOL_SIZE * mu;
        boolean valid = rhoTarget < 1.0;
        double pWait = valid ? erlangC(POOL_SIZE, rhoTarget) : 1.0;
        double eNq = valid ? pWait * rhoTarget / (1.0 - rhoTarget) : Double.NaN;
        double eWqMs = valid ? pWait / (POOL_SIZE * mu * (1.0 - rhoTarget)) * 1000.0 : Double.NaN;
        double eWMs = valid ? eWqMs + 1000.0 / mu : Double.NaN;
        String region = pWait < 0.05 ? "Queue-free"
                : pWait < 0.50 ? "Queueing"
                  : pWait < 0.90 ? "Saturated"
                    : "Resource-Exhaustion";
        if (!valid) region = "UNSTABLE (rho>=1, Region IV)";
        return new Prediction(lambda, pWait, eNq, eWqMs, eWMs, region, valid);
    }

    /**
     * Predicted region-boundary arrival rates (Framework Section 3.3 / 5):
     * lambda_0    : P(wait) = 0.05      (SAFE -> EFFICIENT)
     * lambda_warn : E[W_q]  = 1/mu      (latency ~2x baseline; EFFICIENT -> DEGRADED)
     * lambda_deg  : rho     = 0.90
     * Analysis compares these against λ at which measured transitions occur (±10% target).
     */
    private void writeBoundaryPredictions() throws Exception {
        double lam0 = bisectLambda(l -> erlangC(POOL_SIZE, l / (POOL_SIZE * mu)) - 0.05);
        double lamWarn = bisectLambda(l -> {
            double rho = l / (POOL_SIZE * mu);
            return erlangC(POOL_SIZE, rho) / (POOL_SIZE * mu * (1.0 - rho)) - 1.0 / mu;
        });
        double lamDeg = 0.90 * POOL_SIZE * mu;
        try (PrintWriter w = openCsv(FILE_BOUND)) {
            w.println("Boundary,Condition,Predicted_Lambda_rps,Predicted_Rho");
            w.printf(Locale.US, "n0,P(wait)=0.05,%.2f,%.4f%n", lam0, lam0 / (POOL_SIZE * mu));
            w.printf(Locale.US, "n_warn,E[Wq]=1/mu,%.2f,%.4f%n", lamWarn, lamWarn / (POOL_SIZE * mu));
            w.printf(Locale.US, "n_deg,rho=0.90,%.2f,%.4f%n", lamDeg, 0.90);
        }
        System.out.printf("  [BOUNDARIES] lambda_0=%.1f  lambda_warn=%.1f  lambda_deg=%.1f rps%n",
                lam0, lamWarn, lamDeg);
    }

    /**
     * Bisection on lambda in (0, c*mu) for f(lambda) = 0, f increasing.
     */
    private double bisectLambda(java.util.function.DoubleUnaryOperator f) {
        double lo = 1e-6, hi = POOL_SIZE * mu * 0.9999;
        for (int i = 0; i < 200; i++) {
            double mid = (lo + hi) / 2;
            if (f.applyAsDouble(mid) < 0) lo = mid;
            else hi = mid;
        }
        return (lo + hi) / 2;
    }

    // ===================================================================
    // ONE MEASUREMENT CELL  (open-loop Poisson at fixed lambda)
    // ===================================================================

    private RunResult runCell(Mode mode, double lambda) throws Exception {
        setPoolSize(POOL_SIZE);
        System.gc();
        Thread.sleep(800);

        ExecutorService executor = (mode == Mode.VT)
                ? Executors.newVirtualThreadPerTaskExecutor()
                : Executors.newThreadPerTaskExecutor(
                Thread.ofPlatform().name("pt-req-", 0).factory());

        final long warmupNanos = TimeUnit.SECONDS.toNanos(WARMUP_SECONDS);
        final long measureNanos = TimeUnit.SECONDS.toNanos(MEASURE_SECONDS);
        final long t0 = System.nanoTime();
        final long measureStart = t0 + warmupNanos;
        final long measureEnd = measureStart + measureNanos;

        final List<Long> latencies = Collections.synchronizedList(new ArrayList<>());
        final AtomicInteger inFlight = new AtomicInteger();
        final AtomicInteger dispatchedMeas = new AtomicInteger();
        final AtomicInteger completedMeas = new AtomicInteger();
        final AtomicInteger successMeas = new AtomicInteger();
        final AtomicInteger rejected = new AtomicInteger();
        final AtomicLong firstMeasDispatch = new AtomicLong(0);
        final AtomicLong lastMeasDispatch = new AtomicLong(0);

        // --- snapshot GC counters BEFORE measurement window ---
        GcSnapshot gcBefore = snapshotGc();
        long heapAtWindowStart = captureSystem().heapMb;

        // --- background sampler: Hikari pending (ground-truth N_q), heap, threads ---
        final List<Long> nqSamples = Collections.synchronizedList(new ArrayList<>());
        final List<Long> heapSamples = Collections.synchronizedList(new ArrayList<>());
        final List<Long> threadSamples = Collections.synchronizedList(new ArrayList<>());
        final Thread sampler = Thread.ofPlatform().daemon().name("sweep-sampler").start(() -> {
            int tick = 0;
            while (!Thread.currentThread().isInterrupted()) {
                long now = System.nanoTime();
                if (now >= measureStart && now < measureEnd) {
                    nqSamples.add(getHikariPending());
                    if (++tick % SYS_SAMPLE_TICKS == 0) {
                        SystemSnapshot s = captureSystem();
                        heapSamples.add(s.heapMb);
                        threadSamples.add((long) s.threadCount);
                    }
                }
                if (now >= measureEnd) break;
                try {
                    Thread.sleep(SAMPLE_MS);
                } catch (InterruptedException e) {
                    break;
                }
            }
        });

        // --- dispatcher: exponential inter-arrival gaps, absolute-deadline scheduling ---
        // If the dispatcher falls behind (park granularity ~1 ms on some OSes), it dispatches
        // immediately, preserving the mean rate; realized-gap CV is reported as the A1 check.
        final List<Long> realizedGaps = new ArrayList<>();
        long nextDeadline = t0;
        long prevDispatch = -1;
        ThreadLocalRandom rnd = ThreadLocalRandom.current();
        while (nextDeadline < measureEnd) {
            long now = System.nanoTime();
            while (now < nextDeadline) {
                long remaining = nextDeadline - now;
                // Coarse OS timers (~15 ms on Windows) clump arrivals (observed gap CV 1.5-3.0).
                // Park until 2 ms before the deadline, then busy-spin for sub-ms precision.
                if (remaining > 2_000_000L) LockSupport.parkNanos(remaining - 2_000_000L);
                else Thread.onSpinWait();
                now = System.nanoTime();
            }
            final long dispatchTime = now;
            final boolean inWindow = dispatchTime >= measureStart && dispatchTime < measureEnd;
            if (inWindow) {
                if (prevDispatch > 0) realizedGaps.add(dispatchTime - prevDispatch);
                prevDispatch = dispatchTime;
                firstMeasDispatch.compareAndSet(0, dispatchTime);
                lastMeasDispatch.set(dispatchTime);
            }
            if (inFlight.get() >= MAX_IN_FLIGHT) {
                if (inWindow) rejected.incrementAndGet();
            } else {
                inFlight.incrementAndGet();
                if (inWindow) dispatchedMeas.incrementAndGet();
                try {
                    executor.submit(() -> {
                        long s = System.nanoTime();
                        boolean ok = false;
                        try {
                            performIoTask();
                            ok = true;
                        } catch (Exception ignored) {
                        } finally {
                            long lat = System.nanoTime() - s;
                            if (inWindow) {
                                latencies.add(lat);
                                completedMeas.incrementAndGet();
                                if (ok) successMeas.incrementAndGet();
                            }
                            inFlight.decrementAndGet();
                        }
                    });
                } catch (Throwable t) {
                    // PT mode under deep overload: native thread creation can fail (T_max).
                    // Recorded as rejection — this IS the Region IV phenomenon, not a crash.
                    inFlight.decrementAndGet();
                    if (inWindow) {
                        dispatchedMeas.decrementAndGet();
                        rejected.incrementAndGet();
                    }
                }
            }
            // Exponential(lambda) gap; clamp at 10 s to avoid pathological stalls at tiny lambda
            double gapSec = Math.min(-Math.log(1.0 - rnd.nextDouble()) / lambda, 10.0);
            nextDeadline += (long) (gapSec * 1e9);
        }

        // --- drain in-flight requests (their latencies still count for the window) ---
        long drainDeadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(DRAIN_TIMEOUT_S);
        while (inFlight.get() > 0 && System.nanoTime() < drainDeadline) Thread.sleep(100);
        sampler.interrupt();
        executor.shutdownNow();

        // --- snapshot GC counters AFTER measurement window ---
        GcSnapshot gcAfter = snapshotGc();
        long heapAtWindowEnd = captureSystem().heapMb;

        // --- GC delta metrics for this replicate ---
        long gcCollections = gcAfter.totalCollections - gcBefore.totalCollections;
        long gcPauseTotalMs = gcAfter.totalPauseMs - gcBefore.totalPauseMs;
        double gcPauseMeanMs = gcCollections > 0 ? (double) gcPauseTotalMs / gcCollections : 0.0;
        double heapDeltaMb = heapAtWindowEnd - heapAtWindowStart;
        // Allocation rate: use heap max - heap at window start as proxy
        //   (true allocation rate requires GC allocation counters not available in standard MXBean;
        //    heapDeltaMb / windowSec gives net accumulation rate; see §4.3 note in paper).
        double allocRateMbS = heapSamples.isEmpty() ? 0
                : (heapSamples.stream().mapToLong(Long::longValue).max().orElse(0)
                   - heapAtWindowStart) / (double) MEASURE_SECONDS;

        // --- reduce ---
        double windowSec = MEASURE_SECONDS;
        double achievedLambda = dispatchedMeas.get() / windowSec;

        double gapMean = realizedGaps.stream().mapToLong(Long::longValue).average().orElse(0);
        double gapStd = stddevL(realizedGaps, gapMean);
        double gapCv = gapMean > 0 ? gapStd / gapMean : 0;

        List<Long> sorted = new ArrayList<>(latencies);
        sorted.sort(Long::compare);
        double meanMs = sorted.isEmpty() ? 0
                : sorted.stream().mapToLong(Long::longValue).average().orElse(0) / 1e6;
        double p99Ms = sorted.isEmpty() ? 0
                : sorted.get(Math.min(sorted.size() - 1, (int) (sorted.size() * 0.99))) / 1e6;

        double nqMean = nqSamples.stream().mapToLong(Long::longValue).average().orElse(0);
        long nqMax = nqSamples.stream().mapToLong(Long::longValue).max().orElse(0);
        double heapMean = heapSamples.stream().mapToLong(Long::longValue).average().orElse(0);
        long heapMax = heapSamples.stream().mapToLong(Long::longValue).max().orElse(0);
        double thrMean = threadSamples.stream().mapToLong(Long::longValue).average().orElse(0);
        long thrMax = threadSamples.stream().mapToLong(Long::longValue).max().orElse(0);

        // Little's Law internal consistency: N_q ?= lambda * W_q  (W_q = W - E[S])
        double wqMeasSec = Math.max(meanMs - baselineMeanMs, 0) / 1000.0;
        double littleNq = achievedLambda * wqMeasSec;

        double throughput = completedMeas.get() / windowSec;
        double successPct = dispatchedMeas.get() > 0
                ? successMeas.get() * 100.0 / dispatchedMeas.get() : 0;

        System.out.printf(
                "  lambda: target=%.1f achieved=%.1f (CV=%.2f) | tp=%.1f rps | mean=%.0f ms " +
                        "P99=%.0f ms | Nq=%.1f (max %d, Little=%.1f) | heap=%.0f MB | threads=%.0f (max %d)" +
                        " | GC: %d events %.0f ms | allocRate=%.1f MB/s%s%n",
                lambda, achievedLambda, gapCv, throughput, meanMs, p99Ms,
                nqMean, nqMax, littleNq, heapMean, thrMean, thrMax,
                gcCollections, (double) gcPauseTotalMs, allocRateMbS,
                rejected.get() > 0 ? " | REJECTED=" + rejected.get() : "");

        return new RunResult(lambda, achievedLambda, gapCv,
                dispatchedMeas.get(), completedMeas.get(), rejected.get(), successPct,
                throughput, meanMs, p99Ms, nqMean, nqMax, littleNq,
                heapMean, heapMax, thrMean, thrMax,
                gcCollections, gcPauseTotalMs, gcPauseMeanMs, allocRateMbS, heapDeltaMb);
    }

    /**
     * Service task. The simulated I/O delay runs INSIDE the database (WAITFOR DELAY),
     * so the HikariCP connection is genuinely OCCUPIED for the whole service time.
     * E[S] therefore equals connection hold time - the quantity M/M/c actually models.
     * <p>
     * Previous version slept AFTER the query returned the connection to the pool:
     * hold time was ~13 ms, true capacity ~3,800 rps, and the entire first sweep ran
     * at effective rho <= 0.18 - no queueing ever formed (run 20260708_201658).
     */
    private void performIoTask() throws Exception {
        try (Connection conn = dataSource.getConnection();
             Statement st = conn.createStatement()) {
            //            try (ResultSet rs = st.executeQuery(
//                    "SELECT TOP 20 * FROM invoices WHERE store_id = " + TEST_STORE_ID)) {
//                while (rs.next()) { /* drain */ }
//            }
            try {
                st.execute(WAITFOR_SQL);
                try (ResultSet rs = st.executeQuery(
                        "SELECT * FROM invoices WHERE store_id = " + TEST_STORE_ID + " LIMIT 20")) {
                    while (rs.next()) ;
                }
            } catch (Exception e) {
                System.err.println("performIoTask error: " + e.getMessage());
                e.printStackTrace();
                throw e;
            }
        }
    }

